let currentLang = localStorage.getItem('topdik_lang') || 'uz';

function t(key, params = {}) {
  let text = translations[currentLang]?.[key] || translations.en[key] || key;
  Object.keys(params).forEach(k => {
    text = text.replace(`{${k}}`, params[k]);
  });
  return text;
}

function setLanguage(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  localStorage.setItem('topdik_lang', lang);
  document.documentElement.lang = lang;
  updatePageTranslations();
  document.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
}

function updatePageTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const params = {};
    if (el.dataset.i18nParams) {
      try { Object.assign(params, JSON.parse(el.dataset.i18nParams)); } catch(e) {}
    }
    el.textContent = t(key, params);
  });
  
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
  });
  
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.title = t(el.getAttribute('data-i18n-title'));
  });
  
  // Update select options if needed
  const langSelect = document.getElementById('langSelect');
  if (langSelect) langSelect.value = currentLang;
}

// Init
document.addEventListener('DOMContentLoaded', () => {
  document.documentElement.lang = currentLang;
  updatePageTranslations();
});
